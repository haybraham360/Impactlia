import path from "node:path";
import type { Node } from "web-tree-sitter";
import type { ResolvedReference } from "../graph";
import type { Resolution } from "../resolve";
import {
  restated,
  storedStatements,
  type FileReading,
  type LanguageAdapter,
  type LanguageContext,
} from "./adapter";
import { filesNamed, joinPath, parentOf, readProjectFile } from "./repository-text";
import { compact, lineOf, readTrees } from "./syntax-tree";
import type { Grammars } from "./tree-sitter";

// Rust, read with tree-sitter's Rust grammar. A crate's files form a module
// tree, and two statements link them:
//
//   mod name;                → "mod": the file that is the child module,
//                              name.rs or name/mod.rs beside it (or the file
//                              a #[path = "..."] attribute names)
//   use crate::a::b::C;      → "use": the deepest module file the path
//   use super::x; self::x;     reaches; C itself may be an item inside it
//   use other_crate::a;      → the same, from the root of a crate of this
//                              workspace (a Cargo.toml's [package] name)
//
// Each crate root is found from its Cargo.toml: src/lib.rs, src/main.rs,
// and every file directly in src/bin, tests, examples and benches. A path
// starting with std, core, alloc, proc_macro or test is the standard
// library's; one naming no crate or module of the repository is a
// third-party crate's. Paths written out in code without `use`, and modules
// generated by macros, are not read.

type RustFile = {
  mods: { name: string; pathAttribute: string | null; inside: string[]; line: number }[];
  uses: { segments: string[]; line: number }[];
};

const STANDARD = new Set(["std", "core", "alloc", "proc_macro", "test"]);
const ROOT_FOLDERS = ["bin", "tests", "examples", "benches"];

// Every path a use tree names: `a::{b, c::d}` → [a, b] and [a, c, d].
function pathsInUseTree(node: Node, prefix: string[]): string[][] {
  switch (node.type) {
    case "scoped_use_list": {
      const base = node.childForFieldName("path");
      const list = node.childForFieldName("list");
      const start = base ? [...prefix, ...compact(base).split("::")] : prefix;
      return list ? list.namedChildren.flatMap((child) => pathsInUseTree(child, start)) : [start];
    }
    case "use_list":
      return node.namedChildren.flatMap((child) => pathsInUseTree(child, prefix));
    case "use_as_clause": {
      const base = node.childForFieldName("path");
      return base ? [[...prefix, ...compact(base).split("::")]] : [];
    }
    case "use_wildcard": {
      const base = node.namedChildren[0];
      return [base ? [...prefix, ...compact(base).split("::")] : prefix];
    }
    default:
      return [[...prefix, ...compact(node).split("::")]];
  }
}

function readRustFile(root: Node): RustFile {
  const file: RustFile = { mods: [], uses: [] };
  const visit = (node: Node, inside: string[]) => {
    for (const child of node.namedChildren) {
      if (child.type === "mod_item") {
        const name = child.childForFieldName("name")?.text;
        if (!name) continue;
        const body = child.childForFieldName("body");
        if (body) {
          visit(body, [...inside, name]);
          continue;
        }
        // #[path = "..."] written just before it.
        const previous = child.previousNamedSibling;
        const attribute = previous?.type === "attribute_item" ? /^#\[\s*path\s*=\s*"([^"]+)"\s*\]$/.exec(previous.text) : null;
        file.mods.push({ name, pathAttribute: attribute ? attribute[1] : null, inside, line: lineOf(child) });
      } else if (child.type === "use_declaration") {
        const argument = child.childForFieldName("argument");
        if (!argument) continue;
        for (const segments of pathsInUseTree(argument, [])) {
          file.uses.push({ segments: segments.filter((segment) => segment !== ""), line: lineOf(child) });
        }
      } else if (child.type === "extern_crate_declaration") {
        const name = child.childForFieldName("name")?.text;
        if (name) file.uses.push({ segments: [name], line: lineOf(child) });
      } else if (child.type === "function_item" || child.type === "impl_item" || child.type === "declaration_list" || child.type === "block") {
        // `use` inside a function or impl block still links the file.
        visit(child, inside);
      }
    }
  };
  visit(root, []);
  return file;
}

const modSpecifier = (mod: RustFile["mods"][number]) =>
  mod.pathAttribute ?? [...mod.inside, mod.name].join("::");

export function rustAdapter(grammars: Grammars): LanguageAdapter {
  return {
    languages: ["rust"],
    read({ root, walk, files, texts, stored }: LanguageContext) {
      const included = new Set(walk.sourceFiles);
      // Each crate's folder and the name other crates use it by.
      const crates = filesNamed(walk, "Cargo.toml").flatMap((manifest) => {
        const text = readProjectFile(root, manifest) ?? "";
        const section = /^\s*\[package\]\s*$([\s\S]*?)(?=^\s*\[|(?![\s\S]))/m.exec(text)?.[1] ?? "";
        const name = /^\s*name\s*=\s*"([^"]+)"/m.exec(section)?.[1] ?? null;
        return [{ folder: parentOf(manifest), name: name === null ? null : name.replaceAll("-", "_") }];
      });
      crates.sort((a, b) => b.folder.length - a.folder.length);
      const crateOf = (file: string) =>
        crates.find(({ folder }) => folder === "" || file === folder || file.startsWith(`${folder}/`)) ?? null;
      const libraryRoot = (folder: string) =>
        [joinPath(folder, "src/lib.rs"), joinPath(folder, "src/main.rs")].find((candidate) => included.has(candidate)) ?? null;

      // The crate root a file is compiled under.
      function rootOf(file: string): string | null {
        const crate = crateOf(file);
        if (!crate) return null;
        const relative = crate.folder === "" ? file : file.slice(crate.folder.length + 1);
        const [top, second, third] = relative.split("/");
        const area = top === "src" && second === "bin" ? "bin" : top;
        if (ROOT_FOLDERS.includes(area)) {
          const base = area === "bin" ? joinPath(crate.folder, "src/bin") : joinPath(crate.folder, top);
          const first = area === "bin" ? third : second;
          if (first === undefined) return null;
          if (first.endsWith(".rs")) return joinPath(base, first);
          const main = joinPath(base, `${first}/main.rs`);
          return included.has(main) ? main : null;
        }
        return top === "src" ? libraryRoot(crate.folder) : null;
      }

      // The folder a module's children live in.
      const childFolder = (file: string, isRoot: boolean) =>
        isRoot || path.posix.basename(file) === "mod.rs" ? parentOf(file) : file.slice(0, -3);
      const moduleFile = (folder: string, name: string) =>
        [joinPath(folder, `${name}.rs`), joinPath(folder, `${name}/mod.rs`)].find((candidate) => included.has(candidate)) ?? null;

      // The deepest module file a path reaches, from a module's file.
      function descend(start: string, isRoot: boolean, segments: string[]): string {
        let file = start;
        let folder = childFolder(start, isRoot);
        for (const segment of segments) {
          const next = moduleFile(folder, segment);
          if (!next) break;
          file = next;
          folder = childFolder(next, false);
        }
        return file;
      }

      // A module's path from its crate root: src/a/b.rs → [a, b].
      function modulePath(file: string, rootFile: string): string[] | null {
        const base = parentOf(rootFile);
        if (file === rootFile) return [];
        if (!file.startsWith(base === "" ? "" : `${base}/`)) return null;
        const relative = (base === "" ? file : file.slice(base.length + 1)).replace(/\.rs$/, "").replace(/(^|\/)mod$/, "");
        return relative === "" ? [] : relative.split("/");
      }

      function resolveUse(file: string, segments: string[]): Resolution {
        const rootFile = rootOf(file);
        const [first, ...rest] = segments;
        const internal = (target: string): Resolution => ({ status: "internal", target, via: "module-tree" });
        if (first === "crate" || first === "self" || first === "super") {
          if (!rootFile) {
            return { status: "unresolved", reason: "file-not-found", detail: `${file} is not under a crate root this repository's Cargo.toml files define, so "${first}" cannot be followed.` };
          }
          let own = modulePath(file, rootFile);
          if (own === null) own = [];
          let from: string[] = [];
          let remaining = rest;
          if (first === "self") from = own;
          if (first === "super") {
            let up = 1;
            while (remaining[0] === "super") {
              up += 1;
              remaining = remaining.slice(1);
            }
            from = own.slice(0, Math.max(0, own.length - up));
          }
          return internal(descend(rootFile, true, [...from, ...remaining]));
        }
        // A child module of the file's own module, which is in scope by name.
        // A file under no crate is read as a root, like rustc given it alone.
        const isRoot = rootFile === file || rootFile === null;
        if (moduleFile(childFolder(file, isRoot), first)) return internal(descend(file, isRoot, segments));
        const crate = crates.find(({ name }) => name === first);
        const library = crate ? libraryRoot(crate.folder) : null;
        if (library) return internal(descend(library, true, rest));
        if (STANDARD.has(first)) return { status: "external", externalKind: "builtin", packageName: first };
        return { status: "external", externalKind: "package", packageName: first };
      }

      // A `mod` is stored as its path attribute when it has one ("x.rs"),
      // else as its module path inside the file ("outer::name" for one
      // declared inside an inline `mod outer { }`), which is all that is
      // needed to find it again.
      function resolveMod(file: string, specifier: string): Resolution {
        const isRoot = rootOf(file) === file || rootOf(file) === null;
        if (specifier.includes("/") || specifier.endsWith(".rs")) {
          const candidate = path.posix.normalize(joinPath(parentOf(file), specifier));
          return included.has(candidate)
            ? { status: "internal", target: candidate, via: "module-tree" }
            : { status: "unresolved", reason: "file-not-found", detail: `No file at ${joinPath(parentOf(file), specifier)}.` };
        }
        const segments = specifier.split("::");
        const name = segments.pop() ?? specifier;
        const folder = joinPath(childFolder(file, isRoot), segments.join("/")).replace(/\/$/, "");
        const target = moduleFile(folder, name);
        return target
          ? { status: "internal", target, via: "module-tree" }
          : { status: "unresolved", reason: "file-not-found", detail: `No ${name}.rs or ${name}/mod.rs in ${folder || "the repository root"}.` };
      }

      const trees = readTrees(grammars.rust, "Rust", files, texts, (_file, tree) => readRustFile(tree));
      const readings = new Map<string, FileReading>();
      for (const [file, { parseStatus, parseErrors, value }] of trees) {
        const references: ResolvedReference[] = [];
        if (value) {
          for (const mod of value.mods) {
            const specifier = modSpecifier(mod);
            references.push({
              source: file,
              site: { kind: "mod", specifier, expression: null, line: mod.line, typeOnly: false },
              resolution: resolveMod(file, specifier),
            });
          }
          for (const use of value.uses) {
            const resolution = resolveUse(file, use.segments);
            if (resolution.status === "internal" && resolution.target === file) continue;
            references.push({
              source: file,
              site: { kind: "use", specifier: use.segments.join("::"), expression: null, line: use.line, typeOnly: false },
              resolution,
            });
          }
        }
        readings.set(file, { parseStatus, parseErrors, references });
      }
      for (const [file, references] of stored) {
        const resolved = storedStatements(references).flatMap((statement) => {
          const { site } = statement[0];
          if (site.specifier === null) return statement;
          if (site.kind === "mod") return restated(statement, [resolveMod(file, site.specifier)]);
          const resolution = resolveUse(file, site.specifier.split("::"));
          return resolution.status === "internal" && resolution.target === file ? [] : restated(statement, [resolution]);
        });
        readings.set(file, { parseStatus: "parsed", parseErrors: [], references: resolved });
      }
      return { files: readings, resolutionConfigs: [] };
    },
  };
}
