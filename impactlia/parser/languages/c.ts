// C and C++, read with tree-sitter's C and C++ grammars. Only #include
// directives are read: they are the files' dependencies on each other, and
// they are what tree-sitter reads reliably without running the
// preprocessor. Elsewhere a macro can look like a syntax error the compiler
// would never see, so syntax errors are not recorded for these languages.
// An #include inside #if is read like any other: it is a dependency in at
// least one configuration.
//
//   #include "x.h"   → the folder of the including file, then the include
//                       folders, then the repository root
//   #include <x.h>   → the include folders, then the repository root
//
// The include folders are every folder named include or inc, in path order:
// the build system's own search paths (CMake, Make, Bazel) are not read. A
// header found nowhere in the repository is the standard library's when it
// is a standard header, and an external library's otherwise. A quoted
// include that is found nowhere is unresolved: it is usually generated by
// the build.

const C_HEADERS = [
  "assert.h", "complex.h", "ctype.h", "errno.h", "fenv.h", "float.h", "inttypes.h", "iso646.h",
  "limits.h", "locale.h", "math.h", "setjmp.h", "signal.h", "stdalign.h", "stdarg.h", "stdatomic.h",
  "stdbit.h", "stdbool.h", "stdckdint.h", "stddef.h", "stdint.h", "stdio.h", "stdlib.h",
  "stdnoreturn.h", "string.h", "tgmath.h", "threads.h", "time.h", "uchar.h", "wchar.h", "wctype.h",
];
// POSIX and the usual system headers, which no repository provides.
const SYSTEM_HEADERS = /^(sys|arpa|netinet|net|linux|asm|mach|windows|winapi|bits)\/|^(unistd|fcntl|pthread|dirent|dlfcn|poll|sched|semaphore|signal|strings|syslog|termios|netdb|pwd|grp|regex|glob|getopt|windows|winsock2?|io|direct|malloc|alloca|execinfo|spawn|utime|wordexp)\.h$/;
const CPP_HEADERS = [
  "algorithm", "any", "array", "atomic", "barrier", "bit", "bitset", "cassert", "cctype", "cerrno",
  "cfenv", "cfloat", "charconv", "chrono", "cinttypes", "climits", "clocale", "cmath", "codecvt",
  "compare", "complex", "concepts", "condition_variable", "coroutine", "csetjmp", "csignal",
  "cstdarg", "cstddef", "cstdint", "cstdio", "cstdlib", "cstring", "ctime", "cuchar", "cwchar",
  "cwctype", "deque", "exception", "execution", "expected", "filesystem", "format", "forward_list",
  "fstream", "functional", "future", "generator", "initializer_list", "iomanip", "ios", "iosfwd",
  "iostream", "istream", "iterator", "latch", "limits", "list", "locale", "map", "mdspan", "memory",
  "memory_resource", "mutex", "new", "numbers", "numeric", "optional", "ostream", "print", "queue",
  "random", "ranges", "ratio", "regex", "scoped_allocator", "semaphore", "set", "shared_mutex",
  "source_location", "span", "spanstream", "sstream", "stack", "stacktrace", "stdexcept",
  "stdfloat", "stop_token", "streambuf", "string", "string_view", "syncstream", "system_error",
  "thread", "tuple", "type_traits", "typeindex", "typeinfo", "unordered_map", "unordered_set",
  "utility", "valarray", "variant", "vector", "version",
];
const STANDARD = new Set([...C_HEADERS, ...CPP_HEADERS]);
const INCLUDE_FOLDER = /(^|\/)(include|inc)$/;

type Include = { path: string; system: boolean; line: number };

function readIncludes(root: Node): Include[] {
  return root.descendantsOfType("preproc_include").flatMap((node): Include[] => {
    const target = node.childForFieldName("path");
    if (!target) return [];
    if (target.type === "system_lib_string") return [{ path: target.text.slice(1, -1).trim(), system: true, line: lineOf(node) }];
    if (target.type === "string_literal") return [{ path: target.text.slice(1, -1).trim(), system: false, line: lineOf(node) }];
    // `#include MACRO` names its file through the preprocessor.
    return [];
  });
}

// "a/./b/../c.h" → "a/c.h"; null when it climbs out of the repository.
function normalise(relative: string): string | null {
  const parts: string[] = [];
  for (const part of relative.split("/")) {
    if (part === "" || part === ".") continue;
    if (part === "..") {
      if (parts.length === 0) return null;
      parts.pop();
    } else parts.push(part);
  }
  return parts.join("/");
}

export function cAdapter(grammars: Grammars): LanguageAdapter {
  return {
    languages: ["c", "cpp"],
    read({ walk, files, texts, languageOf, stored }: LanguageContext) {
      const included = new Set(walk.sourceFiles);
      const folders = new Set<string>();
      for (const file of walk.sourceFiles) {
        for (let folder = parentOf(file); folder !== ""; folder = parentOf(folder)) folders.add(folder);
      }
      const includeFolders = [...folders].filter((folder) => INCLUDE_FOLDER.test(folder)).sort();

      function resolve(file: string, include: Include): Resolution {
        const searched = [...(include.system ? [] : [parentOf(file)]), ...includeFolders, ""];
        for (const [at, folder] of searched.entries()) {
          const candidate = normalise(joinPath(folder, include.path));
          if (candidate !== null && included.has(candidate)) {
            const nearest = !include.system && at === 0;
            return { status: "internal", target: candidate, via: nearest ? "relative" : "include-directory" };
          }
          // There, but kept out of the graph: an .inc file, or in a build folder.
          if (candidate !== null && walk.skippedFiles.has(candidate)) {
            const rule = exclusionOf(walk, candidate);
            if (rule) return { status: "excluded", target: candidate, rule };
          }
        }
        if (STANDARD.has(include.path) || SYSTEM_HEADERS.test(include.path)) {
          return { status: "external", externalKind: "builtin", packageName: include.path };
        }
        if (include.system) {
          return { status: "external", externalKind: "package", packageName: include.path.split("/")[0].replace(/\.h(pp)?$/, "") };
        }
        return {
          status: "unresolved",
          reason: "file-not-found",
          detail: `No file ${include.path} beside ${file}, in an include folder or at the repository root. It may be generated by the build, or found through a search path the build sets.`,
        };
      }

      const readings = new Map<string, FileReading>();
      for (const language of ["c", "cpp"] as const) {
        const own = files.filter((file) => languageOf(file) === language);
        const trees = readTrees(grammars[language], language === "c" ? "C" : "C++", own, texts, (_file, tree) => readIncludes(tree), {
          checkSyntax: false,
        });
        for (const [file, { parseStatus, parseErrors, value }] of trees) {
          const references: ResolvedReference[] = (value ?? []).map((include) => ({
            source: file,
            site: { kind: "include", specifier: include.path, expression: null, line: include.line, typeOnly: false },
            resolution: resolve(file, include),
          }));
          readings.set(file, { parseStatus, parseErrors, references });
        }
      }
      // Stored includes resolved again. Whether one was written <x.h> or
      // "x.h" is not stored; one that led outside the repository is taken as
      // <x.h>, every other as "x.h", which also searches the file's folder.
      for (const [file, references] of stored) {
        const resolved = storedStatements(references).flatMap((statement) => {
          const { site, resolution } = statement[0];
          if (site.specifier === null) return statement;
          const include = { path: site.specifier, system: resolution.status === "external", line: site.line };
          return restated(statement, [resolve(file, include)]);
        });
        readings.set(file, { parseStatus: "parsed", parseErrors: [], references: resolved });
      }
      return { files: readings, resolutionConfigs: [] };
    },
  };
}
